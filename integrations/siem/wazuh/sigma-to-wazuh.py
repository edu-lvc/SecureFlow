#!/usr/bin/env python3
"""Optional stub adapter: Sigma -> Wazuh rule XML.

This script is not a runtime dependency of SecureFlow. It is a translation helper
that produces Wazuh XML rule stubs from Sigma rules generated by SecureFlow.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence


# Coarse mapping from Sigma logsource product/category to Wazuh location hints.
LOGSOURCE_HINTS: Dict[str, str] = {
    "windows": "WinEvtLog",
    "sysmon": "Microsoft-Windows-Sysmon/Operational",
    "webserver": "web-accesslog",
    "okta": "okta",
    "azure": "azure",
}


def _escape_xml(value: str) -> str:
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _load_sigma(path: Path) -> Optional[Dict[str, Any]]:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        return json.loads(text)
    return _load_minimal_yaml(text)


def _load_minimal_yaml(text: str) -> Dict[str, Any]:
    """Parse the small subset of YAML emitted by SecureFlow.

    Supports nested maps and lists. Scalar values are returned as strings.
    """
    data: Dict[str, Any] = {}
    stack: List[Tuple[Dict[str, Any], str, int]] = [(data, "", -1)]

    for raw in text.splitlines():
        if not raw.strip() or raw.strip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip())
        stripped = raw.rstrip().strip()

        if stripped.startswith("- "):
            item = stripped[2:].strip().strip('"')
            # An empty placeholder dict created for a key that is actually a list should be
            # popped so the list is attached to the parent container.
            list_key = ""
            while len(stack) > 1:
                placeholder, key, _ = stack[-1]
                if key != "" and isinstance(placeholder, dict) and not placeholder:
                    stack.pop()
                    list_key = key
                else:
                    break
            parent_container, _, _ = stack[-1]
            if list_key == "":
                continue
            if not isinstance(parent_container.get(list_key), list):
                parent_container[list_key] = []
            parent_container[list_key].append(item)
            continue

        if ":" not in stripped:
            continue
        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip().strip('"')

        while len(stack) > 1 and indent <= stack[-1][2]:
            stack.pop()
        parent, _, _ = stack[-1]

        if value:
            parent[key] = value
        else:
            parent[key] = {}
            stack.append((parent[key], key, indent))

    return data


def _location_hint(logsource: Dict[str, Any]) -> str:
    product = logsource.get("product", "")
    return LOGSOURCE_HINTS.get(product, "custom")


def _level_to_wazuh(level: str) -> str:
    mapping = {
        "informational": "0",
        "low": "3",
        "medium": "5",
        "high": "7",
        "critical": "10",
    }
    return mapping.get(level.lower(), "3")


def _transform(sigma: Dict[str, Any]) -> List[str]:
    rule_id = sigma.get("id", "unknown")
    title = sigma.get("title", "Untitled")
    logsource = sigma.get("logsource", {})
    detection = sigma.get("detection", {})
    level = sigma.get("level", "low")
    tags = sigma.get("tags", [])
    falsepositives = sigma.get("falsepositives", [])
    references = sigma.get("references", [])

    lines: List[str] = [
        '  <!-- Sigma rule: %s -->' % _escape_xml(rule_id),
        '  <rule id="%s" level="%s">' % (_escape_xml(rule_id), _level_to_wazuh(level)),
        '    <description>%s</description>' % _escape_xml(title),
    ]

    location = _location_hint(logsource)
    if location:
        lines.append('    <location>%s</location>' % _escape_xml(location))

    # Emit simple selection matches as field hints.
    for key, value in detection.items():
        if key == "condition":
            lines.append('    <!-- condition: %s -->' % _escape_xml(str(value)))
            continue
        if isinstance(value, dict):
            for field, pattern in value.items():
                lines.append(
                    '    <field name="%s">%s</field>'
                    % (_escape_xml(str(field)), _escape_xml(str(pattern)))
                )
        elif isinstance(value, list):
            lines.append('    <!-- %s selectors: %s -->' % (_escape_xml(key), _escape_xml(str(value))))

    for tag in tags:
        if tag.startswith("attack.t"):
            lines.append('    <mitre>')
            lines.append('      <id>%s</id>' % _escape_xml(tag.split(".")[-1].upper()))
            lines.append('    </mitre>')

    if falsepositives:
        lines.append('    <!-- falsepositives: %s -->' % _escape_xml("; ".join(falsepositives)))
    if references:
        lines.append('    <!-- references: %s -->' % _escape_xml(" ".join(references)))

    lines.append('  </rule>')
    return lines


def convert(sigma_dir: str, out_path: str) -> int:
    source = Path(sigma_dir)
    if not source.is_dir():
        print("sigma-to-wazuh: not a directory: %s" % sigma_dir, file=sys.stderr)
        return 3
    rules: List[str] = [
        '<!-- Generated by SecureFlow Wazuh adapter -->',
        '<!-- Review before deploying to a Wazuh manager -->',
        '<group name="secureflow,">',
    ]
    for path in sorted(source.iterdir()):
        if path.suffix.lower() not in (".yml", ".yaml", ".json"):
            continue
        sigma = _load_sigma(path)
        if not sigma:
            continue
        rules.extend(_transform(sigma))
    rules.append('</group>')
    Path(out_path).write_text("\n".join(rules) + "\n", encoding="utf-8")
    print("Wazuh rule stubs written to %s" % Path(out_path).resolve())
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Convert SecureFlow Sigma rules to Wazuh XML stubs.")
    parser.add_argument("--sigma-out", required=True, help="Directory containing Sigma rules.")
    parser.add_argument("--out", required=True, help="Output Wazuh XML file.")
    args = parser.parse_args(argv)
    return convert(args.sigma_out, args.out)


if __name__ == "__main__":
    sys.exit(main())
